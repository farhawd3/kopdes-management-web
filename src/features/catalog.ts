export function formatChoiceLabel(value: string): string {
  if (!value) return '';
  if (choiceLabels[value]) return choiceLabels[value];
  return value
    .split(' ')
    .map((word) => (word ? word.charAt(0).toUpperCase() + word.slice(1).toLowerCase() : ''))
    .join(' ');
}

